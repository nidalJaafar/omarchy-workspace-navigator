function functions(file, indent) {
  const src = fs.readFileSync(file, 'utf8');
  const re = new RegExp(`^${' '.repeat(indent)}function (\\w+)\\([^]*?^${' '.repeat(indent)}}`, 'gm');
  return [...src.matchAll(re)].map(m => m[0]).join('\n');
}
